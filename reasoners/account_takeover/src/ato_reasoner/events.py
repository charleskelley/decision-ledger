"""ATO Reasoner login event schema and authentication domain enums.

``LoginEvent`` is ATO's own domain event: what the ingestion layer validates
and the feature layer and scorer consume. It is not a framework type. The
assembler (``assembler.build_submission``) turns an event, its features, and
its score into the framework's ``Submission``, which carries the event
itself as opaque ``raw_event`` JSON (DR-31).

``entity_id`` is derived deterministically from ``account_id`` using UUID5,
so any caller can reproduce the framework identity of an account from the
domain business key without a registry lookup.

An event accepts nothing its submission would refuse — a naive timestamp, an
empty ``event_id``, a non-finite coordinate, or a string the ledger cannot
store — so a bad login is rejected when it is parsed (HTTP 422, or dead
letter for the stream consumer), before its features are written.
"""

from __future__ import annotations

import uuid
from enum import StrEnum
from typing import Literal
from uuid import UUID

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    computed_field,
    model_validator,
)

from core.submission import storage_problem

# Stable UUID5 namespace for ATO Reasoner account entity identifiers.
# UUID5(_ATO_ACCOUNT_NS, account_id) produces a reproducible, opaque
# framework UUID for any account business key.
_ATO_ACCOUNT_NS: UUID = UUID("8a1f9b2e-4c3d-5e6f-7a8b-9c0d1e2f3a4b")


class AuthMethod(StrEnum):
    """Authentication method used for a login attempt.

    Attributes:
        PASSWORD: Standard username/password credential pair.
        MFA_TOTP: Time-based One-Time Password (RFC 6238). A short-lived
            numeric code generated by an authenticator app, used as a second
            factor alongside the primary credential.
        MFA_PUSH: Push notification sent to a registered mobile device as a
            second factor. The user approves the notification to complete
            authentication.
        SSO: Single Sign-On via a federated identity provider using SAML or
            OIDC. The provider vouches for the user's identity.
        PASSKEY: FIDO2/WebAuthn passkey — phishing-resistant, passwordless
            credential bound to a hardware authenticator or device biometric.
        MAGIC_LINK: One-time authentication link delivered to a verified email
            address. The link is single-use and time-limited.
    """

    PASSWORD = "PASSWORD"
    MFA_TOTP = "MFA_TOTP"
    MFA_PUSH = "MFA_PUSH"
    SSO = "SSO"
    PASSKEY = "PASSKEY"
    MAGIC_LINK = "MAGIC_LINK"


class AuthOutcome(StrEnum):
    """Outcome of a login authentication attempt.

    Attributes:
        SUCCESS: Authentication completed; a session was created.
        FAILURE: Authentication rejected — incorrect credential, OTP mismatch,
            or biometric failure.
        TIMEOUT: Authentication request expired before the user completed the
            challenge. Most common in MFA_PUSH flows where the user does not
            respond to the push notification.
        BLOCKED: Request rejected by a pre-authentication control — an IP
            block, rate limiter, or a prior BLOCK decision from the pipeline.
    """

    SUCCESS = "SUCCESS"
    FAILURE = "FAILURE"
    TIMEOUT = "TIMEOUT"
    BLOCKED = "BLOCKED"


class Geolocation(BaseModel):
    """Geographic location data attached to a login event.

    Attributes:
        latitude: Latitude in decimal degrees.
        longitude: Longitude in decimal degrees.
        country: ISO 3166-1 alpha-2 country code (e.g., "US", "DE").
        city: City name as resolved by the geolocation provider.
        asn: Autonomous System Number (e.g., "AS15169").
    """

    model_config = ConfigDict(strict=True, frozen=True, allow_inf_nan=False)

    latitude: float
    longitude: float
    country: str
    city: str
    asn: str


class LoginEvent(BaseModel):
    """Validated login event entering the ATO Reasoner pipeline.

    ``entity_id`` is derived deterministically from ``account_id`` via UUID5
    — no registry required. ``account_id`` is retained as a domain attribute
    for application-layer use (Redis keys, log labels, query filters).

    Attributes:
        event_id: Unique, non-empty identifier for this event instance.
        entity_type: Framework subject classification. Always "account" for
            ATO Reasoner login events.
        timestamp: When the login attempt occurred (timezone-aware).
        account_id: Stable ATO domain business key for the account.
        session_id: Identifier for the current session.
        ip_address: Source IP address (IPv4 or IPv6).
        geolocation: Geographic location derived from the source IP.
        device_fingerprint: Stable device identifier.
        user_agent: HTTP User-Agent string.
        auth_method: Authentication method used.
        outcome: Result of the authentication attempt.
        scenario_tag: Generator-only label. Stripped before scoring — never
            reaches the feature layer or scorer.
    """

    model_config = ConfigDict(strict=True, frozen=True, allow_inf_nan=False)

    # Identity the framework submission is built from
    event_id: str = Field(min_length=1)
    entity_type: Literal["account"] = "account"
    timestamp: AwareDatetime

    # Domain identity
    account_id: str
    session_id: str

    # Network
    ip_address: str
    geolocation: Geolocation

    # Device
    device_fingerprint: str
    user_agent: str

    # Auth context
    auth_method: AuthMethod
    outcome: AuthOutcome

    # Generator only — stripped before scoring
    scenario_tag: str | None = None

    @model_validator(mode="after")
    def _storable(self) -> LoginEvent:
        """Every value is one the ledger can store (the submission carries it)."""
        problem = storage_problem(self.model_dump(mode="json"))
        if problem is not None:
            msg = f"the event holds {problem}, which the ledger cannot store"
            raise ValueError(msg)
        return self

    @computed_field
    @property
    def entity_id(self) -> UUID:
        """Framework UUID derived deterministically from account_id."""
        return uuid.uuid5(_ATO_ACCOUNT_NS, self.account_id)
